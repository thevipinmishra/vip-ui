export function previewStyle(
  theme: OfficialTheme,
  appearance: "light" | "dark",
): CSSProperties {
  return {
    ...theme.light,
    ...(appearance === "dark" ? theme.dark : {}),
    colorScheme: appearance,
  } as CSSProperties;
}

export function themeCss(theme: OfficialTheme) {
  const declarations = (tokens: Tokens) =>
    Object.entries(tokens)
      .map(([name, value]) => `  ${name}: ${value};`)
      .join("\n");

  return `/* ${theme.name} by vip/ui. Paste after your existing light and dark theme rules. */\n:root {\n  color-scheme: light;\n${declarations(theme.light)}\n}\n\n.dark {\n  color-scheme: dark;\n${declarations(theme.dark)}\n}\n`;
}

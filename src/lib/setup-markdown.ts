import { installSteps } from "./agent-docs";

const componentsJson = `{
  "$schema": "https://ui.shadcn.com/schema.json",
  "style": "new-york",
  "rsc": false,
  "tsx": true,
  "tailwind": { "css": "src/index.css", "baseColor": "neutral", "cssVariables": true },
  "aliases": { "components": "@/components", "utils": "@/lib/utils" }
}`;

export function buildSetupMarkdown(site: string): string {
  const lines = [
    "# Set up vip/ui",
    "",
    "Do these steps in the root of the app. Use the package runner of the project in place of `npx` if necessary.",
    "",
    "## Setup",
    "",
    "Change only what is missing. If steps 1 to 5 need no changes, the project is ready.",
    "",
    "1. Make sure that the project uses React 19, TypeScript, and Tailwind CSS v4.1 or later. If it does not, stop and tell the user. Do not upgrade or migrate the project without approval.",
    "2. Make sure that an import alias, such as `@/*`, works for the CLI, TypeScript, and the bundler. If the project has an alias, use it.",
    '   - Set `paths` in the root `tsconfig.json`, such as `"@/*": ["./src/*"]`. The CLI reads this file. If it has `references`, also set `paths` in the config of the app, such as `tsconfig.app.json`. Do not add `baseUrl`.',
    "   - Next.js needs no more changes. In Vite, `paths` are not sufficient, even if the build passes. Set the same alias with `resolve.alias`, or set `resolve.tsconfigPaths: true` in Vite 8 or later. In other bundlers, set the alias if they do not read `paths`.",
    "3. If `components.json` exists, keep it. Make sure that `tsx` and `tailwind.cssVariables` are `true`. If they are not, stop and tell the user. Then do [Existing theme](#existing-theme).",
    "4. If `components.json` does not exist, select one path. The stock theme of create-next-app or Vite is not the project's own colors or fonts:",
    '   - **New project with only starter styles:** in Vite, replace the starter global CSS with `@import "tailwindcss";`. Run `npx shadcn@latest init --defaults`. It creates `components.json`, `lib/utils.ts`, and `components/ui/button.tsx`, and installs packages. It also writes a neutral theme, base styles, `.dark` dark mode, and the Geist font. If `--font-sans` then points to itself, set it to the font variable from the layout, such as `var(--font-geist-sans)`.',
    "   - **Project with its own colors or fonts, or if you are not sure:** do not run `init`. Do [Existing theme](#existing-theme).",
    '5. Make sure that `tailwindcss-react-aria-components` is installed. If no CSS loads it, add `@plugin "tailwindcss-react-aria-components";` after the imports in the global CSS.',
    "6. Finish the installation of any items that the user asked for. Then do [Check and report](#check-and-report) one time.",
    "",
    "## Existing theme",
    "",
    "Do not change the values, fonts, or base styles of the project. A theme item that the user asks for is the exception: its colors are intentional.",
    "",
    "1. If `components.json` does not exist, create it:",
    "",
    "   ```json",
    ...componentsJson.split("\n").map((line) => `   ${line}`),
    "   ```",
    "",
    '   Set `tailwind.css` to the file with `@import "tailwindcss"`. In Next.js, this is usually `src/app/globals.css` or `app/globals.css`. Set `rsc` to `true` only for the Next.js App Router. Replace `@` with the alias from step 2 of [Setup](#setup). `lib/utils` is not necessary.',
    "2. If no CSS or Tailwind config sets a `dark` variant, add `@custom-variant dark (@media (prefers-color-scheme: dark));` after the imports. Without it, the CLI changes how `dark:` classes work.",
    `3. Read the full JSON of ${site}/r/base.json, for example with \`curl\`. Do not install it. Its \`cssVars\` have the tokens and default values.`,
    "4. Before you add tokens, list those that are missing for light, dark, and `@theme`. Look in the global CSS, its imports, and the Tailwind config. A value that was in `:root` before your edits is not missing for dark. If the dark colors are only in `.dark`, list `destructive-foreground` and the success, warning, highlight, `chart-6`, shadow, and ease tokens only if the project has them under a different name. `add` brings those that components use.",
    "5. If a color token is not a full color, such as `240 5% 10%`, stop and ask the user.",
    "6. Add only the tokens on that list, with `--` before each name:",
    "   - Add `light` values to the `:root` rule of the project, or to a new one before the dark rules. Add `dark` values to the rule with the dark colors. If the project has one mode, add only the values for that mode to `:root`.",
    "   - Add `theme` values to `@theme inline`.",
    "   - If the project has the same color under a different name, use it for both modes, such as `--primary: var(--brand)` or `--primary: var(--color-primary)`.",
    "   - If `primary`, `secondary`, `accent`, `card`, or `popover` has a project color, such as `var(--brand)`, but no `-foreground`, use `var(--background)` or `var(--foreground)`. For each mode, select the one that is easier to read on that color.",
    "   - If `--radius` is missing, add `--radius: 0.625rem`. Do not add `--radius-*` entries.",
    "",
    "## Add an item",
    "",
    `Do this only for the items that the user asks for. Replace \`<item-url>\` with the registry URL, such as \`${site}/r/button.json\`.`,
    "",
    ...installSteps("<item-url>"),
    "",
    `Import vip/ui components from the \`vip-ui/\` folder in the components alias, such as \`@/components/vip-ui/button\`. Do not import them from \`ui/\`. To find components, read ${site}/llms.txt.`,
    "",
    "## Check and report",
    "",
    "1. Do step 6 of [Add an item](#add-an-item), unless you did it after your last change. If you changed nothing, report errors. Do not fix them.",
    "2. Give one short report for setup and installs:",
    '   - **Found:** the framework, the theme, and what was missing. If the project was ready, say "The project was already ready. Setup changed nothing."',
    "   - **Changed:** files and packages. If dark mode followed the OS and now uses `.dark`, say that it no longer follows the OS.",
    "   - **Checks:** the build and type check results, errors, and files that were not updated.",
    '   - **Next:** what the user can ask, such as "Add the vip/ui Button".',
    "",
    "## Manual",
    "",
    "Use these steps only if you cannot run the shadcn CLI.",
    "",
    "1. Install `tailwindcss-react-aria-components`.",
    "2. Do step 2 of [Setup](#setup) and steps 3 to 6 of [Existing theme](#existing-theme).",
    `3. Add ${site}/r/setup.css after the imports in the global CSS file. Omit the values that the project already sets.`,
    "4. Do the manual steps in the Markdown page of the component, then [Check and report](#check-and-report).",
  ];

  return `${lines.join("\n")}\n`;
}
